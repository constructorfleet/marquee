// Map over items with at most `limit` calls in flight, keeping results in order.
// Used for per-collection requests during sync: firing hundreds at a media
// server at once (a large Kometa setup) makes requests slow enough to time out.
export async function mapLimit<T, R>(items: T[], limit: number, fn: (item: T) => Promise<R>): Promise<R[]> {
  const results = new Array<R>(items.length);
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const i = next++;
      results[i] = await fn(items[i]!);
    }
  };
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}
